import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const CATEGORIES_PATH = resolve(__dirname, '../../todas-dashboard/mcp-server/data/taxonomy/categories.txt');
const GOOGLE_MAPPING_PATH = resolve(__dirname, '../../todas-dashboard/mcp-server/data/taxonomy/google_mapping.txt');
const OUTPUT_PATH = resolve(__dirname, '../src/data/taxonomy.js');

// --- Parse google_mapping.txt ---
// Format: XX : Shopify Path -> GoogleID : Google Path
function parseGoogleMapping(text) {
  const map = new Map();
  for (const line of text.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const arrowIdx = line.indexOf('->');
    if (arrowIdx === -1) continue;
    const left = line.slice(0, arrowIdx).trim();
    const right = line.slice(arrowIdx + 2).trim();
    const shopifyId = left.split(':')[0].trim();
    const googleId = parseInt(right.split(':')[0].trim(), 10);
    if (shopifyId && !isNaN(googleId)) {
      map.set(shopifyId, googleId);
    }
  }
  return map;
}

// --- Parse categories.txt ---
// Format: gid://shopify/TaxonomyCategory/XX : Path > To > Category
function parseCategories(text, googleMap) {
  const categories = [];
  for (const line of text.split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    // Use ' : ' with spaces to avoid matching the colons in the GID URL
    const sepIdx = line.indexOf(' : ');
    if (sepIdx === -1) continue;
    const gid = line.slice(0, sepIdx).trim();
    const fullPath = line.slice(sepIdx + 3).trim();

    // Extract short ID from GID
    const id = gid.replace('gid://shopify/TaxonomyCategory/', '');
    if (!id) continue;

    const segments = fullPath.split(' > ');
    const name = segments[segments.length - 1];
    const level = segments.length;

    // Derive parentId from the short ID pattern (e.g., "aa-1-2" -> "aa-1")
    const lastDash = id.lastIndexOf('-');
    const parentId = lastDash > -1 ? id.slice(0, lastDash) : null;

    const entry = { id, fullPath, name, level, parentId };

    const googleCategoryId = googleMap.get(id);
    if (googleCategoryId !== undefined) {
      entry.googleCategoryId = googleCategoryId;
    }

    categories.push(entry);
  }
  return categories;
}

// --- Main ---
console.log('Reading source files...');
const categoriesText = readFileSync(CATEGORIES_PATH, 'utf-8');
const googleText = readFileSync(GOOGLE_MAPPING_PATH, 'utf-8');

console.log('Parsing google mapping...');
const googleMap = parseGoogleMapping(googleText);
console.log(`  ${googleMap.size} google mappings found`);

console.log('Parsing categories...');
const categories = parseCategories(categoriesText, googleMap);
console.log(`  ${categories.length} categories parsed`);

const topCategories = categories.filter(c => c.level === 1);
console.log(`  ${topCategories.length} top-level categories`);

// --- Generate output ---
// Use short key names for minimal bundle size
// p = fullPath, n = name, l = level, pi = parentId, g = googleCategoryId
const minCategories = categories.map(c => {
  const o = { id: c.id, p: c.fullPath, n: c.name, l: c.level };
  if (c.parentId) o.pi = c.parentId;
  if (c.googleCategoryId !== undefined) o.g = c.googleCategoryId;
  return o;
});

const minTopCategories = topCategories.map(c => {
  const o = { id: c.id, p: c.fullPath, n: c.name };
  if (c.googleCategoryId !== undefined) o.g = c.googleCategoryId;
  return o;
});

const output = `// Auto-generated by scripts/build-taxonomy.js — do not edit manually
// Keys: id, p=fullPath, n=name, l=level, pi=parentId, g=googleCategoryId

export const shopifyCategories = ${JSON.stringify(minCategories)};

export const topCategories = ${JSON.stringify(minTopCategories)};
`;

writeFileSync(OUTPUT_PATH, output, 'utf-8');
const sizeKB = (Buffer.byteLength(output, 'utf-8') / 1024).toFixed(1);
console.log(`\nWrote ${OUTPUT_PATH}`);
console.log(`  File size: ${sizeKB} KB`);
console.log('Done!');
